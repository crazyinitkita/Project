// CyberSentinel AI — domain types
// These mirror the contract used by the existing backend:
//   React frontend -> Node.js/Express -> FastAPI/Random Forest
//   Node.js/Gemma  -> React frontend (explanation only; never a detection)
//
// In this sandbox the Node/Express + FastAPI roles are served by Next.js API
// routes that reproduce the same response shape, so the frontend behaviour is
// real and testable. Swapping to the production backend is a base-URL change.

export type TrafficFeatureMap = Record<string, number>;

/** One traffic-flow sample expressed with the exact trained feature names. */
export interface TrafficSample {
  features: TrafficFeatureMap;
  source?: string;
  notes?: string;
}

/** A single class probability entry. */
export interface ClassProbability {
  label: string;          // original model label, e.g. "Web Attack – XSS"
  display: string;        // clean display label
  probability: number;    // 0..1
  isAttack: boolean;
}

/** Top contributing features for a prediction (local, sample-level). */
export interface FeatureContribution {
  name: string;
  value: number;
  /** relative influence 0..1 within this sample (heuristic, NOT global importance) */
  influence: number;
  direction: "high" | "low" | "normal";
  note: string;
}

export type ThreatLevel = "benign" | "low" | "medium" | "high" | "critical";

/** Response returned by /api/analyze — prediction + explanation contract. */
export interface AnalysisResult {
  requestId: string;
  createdAt: string;
  // ---- Detection (Random Forest role) ----
  predictedLabel: string;        // original model label
  predictedDisplay: string;      // clean display label
  isAttack: boolean;
  threatLevel: ThreatLevel;
  family: string;                // attack family (e.g. "Denial of Service")
  confidence: number;            // top-1 probability, 0..1
  probabilities: ClassProbability[];
  topContributingFeatures: FeatureContribution[];
  // ---- Explanation (Gemma role) ----
  explanation: string;           // markdown, generated by LLM
  explanationSource: "llm" | "fallback";
  investigation: string[];       // safe investigation recommendations
  // ---- Provenance / honesty ----
  modelName: string;
  modelVersion: string;
  dataset: string;
  caveats: string[];
  featureCount: number;
  processingMs: number;
  reviewRequired?: boolean;
  modelScore?: number | null;
  confidenceThreshold?: number;
}

export interface SampleProfile {
  id: string;
  name: string;
  description: string;
  expectedLabel: string;
  expectedDisplay: string;
  features: TrafficFeatureMap;
}

export interface ModelClassInfo {
  label: string;          // original model label
  display: string;        // clean display label
  isAttack: boolean;
  trainingCount: number;
  share: number;          // 0..1 of training sample
  severity: ThreatLevel;
  family: string;
  summary: string;
}

export interface ModelEvaluation {
  modelName: string;
  modelType: string;
  hyperparameters: Record<string, string | number>;
  featureCount: number;
  classCount: number;
  trainingRows: number;
  dataset: string;
  splits: {
    name: string;
    description: string;
    accuracy: number;
    balancedAccuracy: number;
    macroF1: number;
    weightedF1: number;
    sharedGroups: number;
    note: string;
  }[];
  classDistribution: ModelClassInfo[];
  duplicateAudit: {
    exactDuplicateRows: number;
    rowsInRepeatedGroups: number;
    repeatedGroups: number;
    conflictingGroups: number;
    benignVsDosHulkConflicts: number;
    benignVsPortScanConflicts: number;
    note: string;
  };
  globalFeatureImportance: { name: string; importance: number }[];
  plannedWork: string[];
}

export interface ModelInfoResponse {
  evaluation: ModelEvaluation;
  generatedAt: string;
}
